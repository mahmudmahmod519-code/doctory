// ==========================================
// API ROUTES (JSON)
// ==========================================

// POST /api/auth/register/patient
// Register a new patient account.
// Body: { name (required), email (required), password (required, min 6), confirmPassword (required),
//         phone (required, Egyptian format), address (optional) }.
// Returns 201: { status: 'success', message, data: { user } } with user_id, name, email, phone,
// address, role, status and enable_2fa.
// Business rules:
// - The role is forced to 'patient' and the status to 'active'.
// - The email is stored lowercased and must be unique — an existing email returns 409.
// - The password is hashed with bcrypt before it is stored in User.password_hash.
// - A JWT is issued in the HTTP-Only cookie 'session_token' and a refresh token is stored.
// 400 on validation failure, 409 when the email is already registered.
// No authentication required (guest only).

// POST /api/auth/register/doctor
// Register a new doctor account.
// Body (multipart/form-data): { name (required), email (required), phone (required),
//         specialty (required), password (required), confirmPassword (required),
//         syndicate_number (required), working_hours (optional),
//         medical_id (required file — image/png | image/jpeg | image/webp | application/pdf, max 5MB) }.
// Returns 201: { status: 'success', message, data: { user } } with role = 'doctor' and status = 'pending'.
// Business rules:
// - The role is forced to 'doctor' and the status to 'pending' until an admin approves the Medical ID.
// - The Medical ID file is mandatory and is stored for the admin review (the Medical Syndicate ID
//   image link must be protected — never a public static path).
// - The password is hashed with bcrypt before it is stored in User.password_hash.
// - A DoctorPortfolio record is created and linked to the new user.
// - An audit log entry and an in-app notification for the admins are created.
// 400 on validation failure, 409 when the email is already registered.
// No authentication required (guest only).

// POST /api/auth/login
// Authenticate a user and issue the JWT tokens.
// Body: { email (required), password (required) }.
// Returns 200: { status: 'success', message, data: { user } } with user_id, name, email and role.
// Business rules:
// - The Access JWT is set in the HTTP-Only cookie 'session_token' and the refresh token in 'refresh_token'.
// - A suspended or a soft-deleted account cannot log in — it returns 403.
// - last_login is updated on every successful login.
// 400 on validation failure, 401 when the credentials are wrong, 403 when the account is not active.
// No authentication required (guest only).

// POST /api/auth/2fa/verify
// Verify the TOTP code generated by the authenticator app.
// Body: { token (required, exactly 6 digits) }.
// Returns 200: { status: 'success', message }.
// Business rules:
// - Mandatory for the doctor and admin roles, optional for the patient.
// - The code is verified with speakeasy against the secure_key of the user.
// - A valid code completes the login and the session cookies are issued.
// 400 on validation failure, 401 when the code is wrong or expired.
// No authentication required (guest / login flow).

// POST /api/auth/refresh
// Issue a new Access token from a valid refresh token.
// Body: { refresh_token } or the refresh token is read from the HTTP-Only cookie.
// Returns 200: { status: 'success', message, data: { token } }.
// Business rules:
// - The refresh token must exist, must not be revoked and must not be expired.
// - The used token is rotated: the old one is revoked and a new one is stored.
// - The new Access token is set in the 'session_token' cookie.
// 401 when the token is missing, revoked or expired.
// No authentication required (guest).

// GET /api/auth/me
// Get the information of the current authenticated user.
// Query: none.
// Returns 200: { status: 'success', data: { user } } with user_id, name, email, role, status,
// email_verified and enable_2fa.
// 401 when the session is missing or invalid.
// Requires authentication (any role).

// POST /api/auth/logout
// Revoke the refresh token and clear the HTTP-Only cookies.
// Body: none.
// Returns 200: { status: 'success', message }.
// Business rules: the refresh token of the session is revoked in the database
// and both cookies are cleared.
// Requires authentication (any role).

// POST /api/auth/forgot-password
// Start the password reset flow.
// Body: { email (required) }.
// Returns 200: { status: 'success', message } with the same generic message in every case.
// Business rules:
// - The response never reveals whether the email exists (anti-enumeration rule).
// - A random reset token is stored on the user with a 1 hour expiry.
// - The reset link is sent by email (Nodemailer) and points to /auth/reset-password/:token.
// - The token field on the user is cleared after a successful reset.
// 400 on validation failure.
// No authentication required (guest only).

// POST /api/auth/reset-password
// Set a new password using a valid reset token.
// Body: { token (required), new_password (required, min 6) }.
// Returns 200: { status: 'success', message }.
// Business rules:
// - The token must match the stored token and must be less than 1 hour old.
// - The new password is hashed with bcrypt and the token is cleared.
// - All the refresh tokens of the user are revoked to force a new login.
// 400 when the token is invalid or expired.
// No authentication required (guest only).

// POST /api/auth/change-password
// Change the password from the settings page.
// Body: { current_password (required), new_password (required, min 6) }.
// Returns 200: { status: 'success', message }.
// Business rules:
// - The current password is verified before the update.
// - The new password is hashed with bcrypt and the refresh tokens are revoked.
// 400 on validation failure, 401 when the current password is wrong.
// Requires authentication (any role).

// POST /api/auth/verify-email
// Confirm the account email address.
// Body: { token (required) }.
// Returns 200: { status: 'success', message }.
// Business rules:
// - The token must match the stored verification token.
// - email_verified is set to true on the user and the token is cleared.
// 400 when the token is invalid.
// No authentication required (guest only).

// POST /api/auth/resend-verification
// Send a new email verification link (the previous token is replaced).
// Body: { email (required) }.
// Returns 200: { status: 'success', message } with the same generic message in every case (anti-enumeration).
// Business rules:
// - Only accounts with email_verified = false receive a new link — the response never reveals the account state.
// - A new random token is stored on the user and the link points to /auth/verify-email/:token.
// - Rate limited: one email every 60 seconds per address.
// Used by the "resend" action of views/auth/email-verification.ejs when the link is invalid or expired.
// 400 on validation failure, 429 when the limit is hit.
// No authentication required (guest only).

